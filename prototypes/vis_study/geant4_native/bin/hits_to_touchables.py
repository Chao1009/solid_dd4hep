"""Sum calorimeter energy per module from an EDM4hep file and write a Geant4 vis macro that colours
the hit modules (touchables) by energy.  Runs inside eic_xl after `source thissolid.sh <config>`.

usage: python3 hits_to_touchables.py COMPACT EDM4HEP OUT_MACRO [events=all] [threshold_GeV=0.001]
"""
import sys, math, collections, time
import ROOT  # noqa: F401  (loads cppyy)
import dd4hep
from podio.root_io import Reader

compact, infile, outmac = sys.argv[1:4]
events = sys.argv[4] if len(sys.argv) > 4 else 'all'
thr = float(sys.argv[5]) if len(sys.argv) > 5 else 0.001
t0 = time.time()
desc = dd4hep.Detector.getInstance()
desc.fromXML(compact)
t1 = time.time()

CALOS = {'FAECShowerHits': 'FAECShower', 'LAECShowerHits': 'LAECShower',
         'FAECPreShowerHits': 'FAECPreShower', 'LAECPreShowerHits': 'LAECPreShower'}
world_pv = desc.world().placement()
world_name, world_copy = world_pv.name(), 0          # Geant4 world PV keeps the TGeo name, copy 0

def module_paths(detname):
    """module id -> Geant4 touchable path [(pvname, copy), ...] from the DD4hep DetElement tree"""
    det = desc.detector(detname)
    env = det.placement()
    base = [(world_name, world_copy), (env.name(), env.copyNumber())]
    out = {}
    for kv in det.children():
        de = kv.second
        pv = de.placement()
        out[de.id()] = base + [(pv.name(), pv.copyNumber())]
    return out

energy = collections.defaultdict(float)
paths = {}
reader = Reader(infile)
for i, ev in enumerate(reader.get('events')):
    if events != 'all' and str(i) not in events.split(','):
        continue
    for coll, detname in CALOS.items():
        if coll not in ev.getAvailableCollections():
            continue
        if detname not in paths:
            paths[detname] = module_paths(detname)
        dec = desc.readout(coll).idSpec().decoder()
        for h in ev.get(coll):
            mod = dec.get(h.getCellID(), 'module')
            energy[(detname, mod)] += h.getEnergy()

sel = {k: e for k, e in energy.items() if e >= thr}
emax = max(sel.values()) if sel else 1.0
emin = max(thr, emax * 1e-2)

def heat(f):
    """f in [0,1] -> (r,g,b): pale yellow -> orange -> dark red"""
    stops = [(0.0, (1.0, 0.95, 0.55)), (0.5, (1.0, 0.55, 0.0)), (1.0, (0.6, 0.0, 0.0))]
    for (f0, c0), (f1, c1) in zip(stops, stops[1:]):
        if f <= f1:
            u = (f - f0) / (f1 - f0)
            return tuple(a + (b - a) * u for a, b in zip(c0, c1))
    return stops[-1][1]

lines = [f'# generated by hits_to_touchables.py from {infile} (events={events}); {len(sel)} modules, '
         f'Emax={emax*1e3:.1f} MeV (visible energy), log colour scale down to {emin*1e3:.2f} MeV']
for (detname, mod), e in sorted(sel.items(), key=lambda kv: -kv[1]):
    f = min(1.0, max(0.0, math.log(e / emin) / math.log(emax / emin))) if emax > emin else 1.0
    r, g, b = heat(f)
    path = ' '.join(f'{n} {c}' for n, c in paths[detname][mod])
    lines.append(f'# {detname} module {mod}: {e*1e3:.2f} MeV')
    lines.append(f'/vis/set/touchable {path}')
    lines.append(f'/vis/touchable/set/colour {r:.3f} {g:.3f} {b:.3f} 1')
    lines.append('/vis/touchable/set/forceSolid true')
open(outmac, 'w').write('\n'.join(lines) + '\n')
print(f'geometry {t1-t0:.1f} s, total {time.time()-t0:.1f} s; {len(sel)} modules above {thr*1e3:.1f} MeV '
      f'(of {len(energy)}), Emax {emax*1e3:.1f} MeV -> {outmac}')
